"""Read the Paragon sprite's plan into pg_outline.py (ordinary Python + Pillow + numpy).

  python3 trace_sprite.py [--sprite PATH]
The sprite is left-right symmetric about the .ship centre, so its outline is a
half-width per row: OUTER[i] = (X, h) is the hull's outermost alpha at model X,
averaged over port and starboard and smoothed over five rows. The model reads
these numbers, never the image, so a build needs no install. Re-run only if the
sprite changes; the numbers are committed.
Pixel mapping: col c, row r -> X 174-r-.5, Y 164-c-.5 (centre 164, 190 from the bottom).
"""
from pathlib import Path
import argparse
import os
import sys
import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
GAME = Path(os.environ.get('STARSECTOR_CORE') or (
    '/Applications/Starsector.app/Contents/Resources/Java' if sys.platform == 'darwin'
    else r'C:\Program Files (x86)\Fractal Softworks\Starsector\starsector-core'))
parser = argparse.ArgumentParser()
parser.add_argument('--sprite', default=str(GAME/'graphics'/'ships'/'paragon.png'))
args = parser.parse_args()
alpha = np.array(Image.open(args.sprite).convert('RGBA'))[..., 3] > 127
H, W = alpha.shape
CX, CY = 164, 190
rows = []
for r in range(H):
    cols = np.where(alpha[r])[0]
    if cols.size == 0:
        continue
    port = CX-cols.min()        # Y of the port edge (pixel outer edge)
    star = cols.max()+1-CX      # |Y| of the starboard edge
    rows.append((H-CY-r-.5, (port+star)/2))
xs = np.array([x for x, _ in rows])
hs = np.array([h for _, h in rows])
sm = np.convolve(np.pad(hs, 2, mode='edge'), np.ones(5)/5, mode='valid')


def simplify(pts, tol):
    """Douglas-Peucker on a polyline of (x, h)."""
    if len(pts) < 3:
        return pts
    (x0, y0), (x1, y1) = pts[0], pts[-1]
    dx, dy = x1-x0, y1-y0
    L = (dx*dx+dy*dy)**.5 or 1
    d = [abs(dy*(x-x0)-dx*(y-y0))/L for x, y in pts]
    i = int(np.argmax(d))
    if d[i] <= tol:
        return [pts[0], pts[-1]]
    return simplify(pts[:i+1], tol)[:-1]+simplify(pts[i:], tol)


outer = simplify([(round(float(x), 2), round(float(h), 2)) for x, h in zip(xs, sm)], .8)
# The bow's first rows (X > 166) are the two hardpoint prongs and the prow tip,
# drawn separately; the outline starts where the plan is continuous.
outer = [p for p in outer if p[0] <= 166.5]
text = ['"""Generated by trace_sprite.py from graphics/ships/paragon.png: do not edit by hand.',
        '',
        'OUTER: (model X, half-width) of the outermost alpha, bow to stern, smoothed over five rows."""',
        f'BOW_X = {xs.max()+.5:.1f}',
        f'STERN_X = {xs.min()-.5:.1f}',
        'OUTER = [']
text += [f'    ({x}, {h}),' for x, h in outer]
text += [']', '']
(HERE/'pg_outline.py').write_text('\n'.join(text), encoding='utf-8')
print(len(outer), 'outline points; bow', xs.max(), 'stern', xs.min())
