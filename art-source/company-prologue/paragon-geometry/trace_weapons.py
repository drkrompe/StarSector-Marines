"""Read the Paragon's weapon sprites into pg_weapon_sprites.py (Python with Pillow, numpy, scipy, scikit-image).

  python3 trace_weapons.py
For each weapon of the Elite fit: the turret sprite, upsampled 2x (LANCZOS) and
classified per cell into tones the model builds as stacked plates:
  '.' empty   'd' dark (the recessed base)   'm' mid (a raised course)
  'l' light (the top plates)   'g' blue-white glow   'r' red lamp
the sprite's alpha outline as a simplified polygon in hull units (outline,
holes), which each gun's base plate is built from, plus the .wpn file's turret fire offsets (sprite pixels from the sprite centre,
+x forward, +y port). One sprite pixel is one hull unit, as the game draws it.
The build reads these numbers, never the images. Re-run if the game changes.
"""
from pathlib import Path
import json
import os
import re
import sys
import numpy as np
from PIL import Image
from scipy import ndimage
from skimage import measure

HERE = Path(__file__).resolve().parent
GAME = Path(os.environ.get('STARSECTOR_CORE') or (
    '/Applications/Starsector.app/Contents/Resources/Java' if sys.platform == 'darwin'
    else r'C:\Program Files (x86)\Fractal Softworks\Starsector\starsector-core'))
WEAPONS = ['tachyonlance', 'gravitonbeam', 'taclaser', 'reaper']
UP = 2
TOL = 1.4         # outline simplification, in 2x cells (0.7 sprite px): straight runs, not pixel steps


def wpn(name):
    text = (GAME/'data'/'weapons'/f'{name}.wpn').read_text(encoding='utf-8')
    text = re.sub(r'#.*', '', text)
    def get(key):
        m = re.search(r'"%s"\s*:\s*(\[[^\]]*\]|"[^"]*")' % key, text)
        return json.loads(m.group(1)) if m else None
    return get('turretSprite'), get('turretOffsets') or [0, 0]


out = ['"""Generated by trace_weapons.py from the game\'s weapon sprites: do not edit by hand.',
       '',
       'SPRITES[weapon] = dict(up, size (cells), offsets (fire points, sprite px), rows (top row = forward))."""',
       'SPRITES = {']
for w in WEAPONS:
    sprite, offsets = wpn(w)
    im = Image.open(GAME/sprite).convert('RGBA')
    im = im.resize((im.width*UP, im.height*UP), Image.LANCZOS)
    a = np.array(im).astype(float)
    al, rgb = a[..., 3], a[..., :3]
    lum = rgb.mean(2)
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    cls = np.full(al.shape, '.', dtype='<U1')
    op = al > 110
    cls[op & (lum < 72)] = 'd'
    cls[op & (lum >= 72) & (lum < 150)] = 'm'
    cls[op & (lum >= 150)] = 'l'
    cls[op & (r > 140) & (g < 90) & (b < 90)] = 'r'
    cls[op & (b > 170) & (b-r > 45) & (lum > 120)] = 'g'
    rows = [''.join(row) for row in cls]
    h, w_ = cls.shape

    def units(c):
        return [[round(float(h/2-r-.5)/UP, 2), round(float(w_/2-q-.5)/UP, 2)] for r, q in c[:-1]]
    solid = ndimage.binary_opening(cls != '.', iterations=1)
    lab, n = ndimage.label(solid)
    comp = lab == 1+int(np.argmax(ndimage.sum(solid, lab, range(1, n+1))))
    filled = ndimage.binary_fill_holes(comp)

    def loop(mask):
        c = max(measure.find_contours(np.pad(mask, 1).astype(float), .5), key=len)-1
        return units(measure.approximate_polygon(c, TOL))
    outline = loop(filled)
    hl, nh = ndimage.label(filled & ~comp)
    holes = [loop(hl == k) for k in range(1, nh+1) if (hl == k).sum() >= 8]
    pts = [[round(offsets[i], 2), round(offsets[i+1], 2)] for i in range(0, len(offsets), 2)]
    out.append(f'    {w!r}: dict(up={UP}, size={list(cls.shape[::-1])}, offsets={pts}, sprite={sprite!r},')
    out.append(f'        outline={outline},')
    out.append(f'        holes={holes},')
    out.append('        rows=[')
    out += [f'        {row!r},' for row in rows]
    out.append('    ]),')
    print(w, sprite, im.size, 'offsets', pts, 'opaque', int(op.sum()))
out.append('}')
(HERE/'pg_weapon_sprites.py').write_text('\n'.join(out)+'\n', encoding='utf-8')
