"""Write groups/<group>.py: the Paragon's staining tiles, as world-space box tiles.

  blender --background build/geom/paragon-geometry.blend --python make_groups.py

The Paragon is an overlay hull (surface_hull.OVERLAY): its hex ceramic stays, and a
part tile carries only the finish that belongs to one place on the ship: soot
trails off the drives, heat tint round the emitters and the bow projectors, grime
round the service fields and hatches. So the tiles are few and broad, a box of the
hull seen square-on from above, from either end or from the side. Port tiles are
painted; each starboard tile reuses its port twin mirrored (`skin_from`,
`mirror_u`), the centreline going to the port tile. A tile's members are the
objects a grid of rays from its view hits inside its box on a classed material,
so the tables follow the geometry: rerun this after a rebuild, then
render_parts.py. Unlike the Legion's, nothing is cut along the tile lines: the
Paragon's faceted masses are already fine-grained.
"""
import sys
from pathlib import Path
import bpy
from mathutils import Vector

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import surface_hull as SH  # noqa: E402

BIG = 1e4
# (group, view, part id, (x0, x1), (y0, y1), (z0, z1), what). Port side only.
TILES = [
    ('top', 'top', 'top-stern', (-190, -122), (0, 162), None, 'aft body, drive blocks and port pod tops from above'),
    ('top', 'top', 'top-aft', (-122, -40), (0, 162), None, 'aft quarter of the ring, the pod top service field and the deck aft'),
    ('top', 'top', 'top-mid', (-40, 62), (0, 162), None, 'mid ring, the bore rim and lining, the command deck'),
    ('top', 'top', 'top-bow', (62, 172), (0, 162), None, 'bow, the projector bays, the ring crown service field, the bow guns'),
    ('ends', 'stern', 'end-stern', None, (0, 162), (-40, 45), 'the stern face: drive mouths and pod ends, square-on'),
    ('ends', 'bow', 'end-bow', None, (0, 162), (-40, 45), 'the bow face: the projector bay mouths and the prow, square-on'),
    ('ends', 'side', 'side-aft', (-190, -10), None, (-40, 45), 'the port flank aft: pod and ring walls'),
    ('ends', 'side', 'side-fore', (-10, 172), None, (-40, 45), 'the port flank forward: ring and bow walls'),
]
SHEETS = {'top': {'top-a': ['top-stern', 'top-aft', 'top-mid', 'top-bow']},
          'ends': {'ends-a': ['end-stern', 'end-bow', 'side-aft', 'side-fore']}}
VIEWS = {'top': ('UP_Z', 'DOWN_X', (0, 0, -1)), 'side': ('PORT', 'UP_Z', (0, -1, 0)),
         'bow': ('BOW', 'UP_Z', (-1, 0, 0)), 'stern': ('STERN', 'UP_Z', (1, 0, 0))}
MIRROR_DIR = {'PORT': 'STARBOARD'}
STEP = 2.0
PAD = 12   # parts.py box 'pad': a face must also lie within the box grown by this

dg = bpy.context.evaluated_depsgraph_get()
scene = bpy.context.scene


def members(view, xs, ys, zs):
    """Objects whose classed faces a ray grid from the view hits inside the box."""
    d = Vector(VIEWS[view][2])
    lo = [(xs or (-BIG, BIG))[0], (ys or (-BIG, BIG))[0], (zs or (-BIG, BIG))[0]]
    hi = [(xs or (-BIG, BIG))[1], (ys or (-BIG, BIG))[1], (zs or (-BIG, BIG))[1]]
    axis = [i for i in range(3) if d[i] == 0]
    found = {}
    a = lo[axis[0]] + STEP / 2
    while a < hi[axis[0]]:
        b = lo[axis[1]] + STEP / 2
        while b < hi[axis[1]]:
            o = [0.0, 0.0, 0.0]
            o[axis[0]], o[axis[1]] = a, b
            k = [i for i in range(3) if i not in axis][0]
            o[k] = -d[k] * 400
            hit, loc, nrm, idx, ob, _ = scene.ray_cast(dg, Vector(o), d)
            if hit and ob.type == 'MESH' and abs(nrm.dot(d)) >= 0.62:
                ev = ob.evaluated_get(dg)
                slot = ev.material_slots[ev.data.polygons[idx].material_index] if ev.material_slots else None
                if slot and slot.material and slot.material.name in SH.MATERIAL_CLASS:
                    found[ob.name] = found.get(ob.name, 0) + 1
            b += STEP
        a += STEP
    return sorted(n for n, c in found.items() if c >= 4), (lo, hi)


def fmt_box(lo, hi):
    f = lambda v: 'BIG' if v >= BIG else '-BIG' if v <= -BIG else f'{v:g}'
    return f"{{'box': (({f(lo[0])}, {f(lo[1])}, {f(lo[2])}), ({f(hi[0])}, {f(hi[1])}, {f(hi[2])})), 'pad': {PAD}}}"


def mirror_name(n):
    return n.replace('port', '\0').replace('starboard', 'port').replace('\0', 'starboard').replace(
        'Port', '\0').replace('Starboard', 'Port').replace('\0', 'Starboard')


names = set(o.name for o in bpy.data.objects)
for group in SHEETS:
    lines = [f'"""{group}: the Paragon\'s staining tiles, seen square-on (generated by ../make_groups.py; rerun it, do not edit)."""',
             'from parts_common import PORT, STARBOARD, UP_Z, DOWN_Z, BOW, STERN, DOWN_X',
             '', f'BIG = {BIG:g}', '', 'PARTS = {']
    for g, view, pid, xs, ys, zs, what in TILES:
        if g != group:
            continue
        objs, (lo, hi) = members(view, xs, ys, zs)
        dirn, up, _ = VIEWS[view]
        lines.append(f"    '{pid}': dict(members=[{', '.join(f'({n!r}, {fmt_box(lo, hi)})' for n in objs)}],")
        lines.append(f"                 dir={dirn}, up={up}, cone=.6, what={what!r}),")
        mlo, mhi = [lo[0], -hi[1], lo[2]], [hi[0], -lo[1], hi[2]]
        if view == 'side':
            mlo[1], mhi[1] = -BIG, BIG
        mobjs = [n for n in (mirror_name(n) for n in objs) if n in names]
        mdir = MIRROR_DIR.get(dirn, dirn)
        lines.append(f"    '{pid}-stbd': dict(members=[{', '.join(f'({n!r}, {fmt_box(mlo, mhi)})' for n in mobjs)}],")
        lines.append(f"                 dir={mdir}, up={up}, cone=.6, skin_from='{pid}', mirror_u=True,")
        lines.append(f"                 what={(what + ' (starboard mirror)')!r}),")
        print('SURF', group, pid, len(objs), 'objects')
    lines += ['}', '', 'SHEETS = {'] + [f"    '{s}': {ps!r}," for s, ps in SHEETS[group].items()] + ['}', '']
    (HERE / 'groups' / f'{group}.py').write_text('\n'.join(lines), encoding='utf-8')
