/**
 * The company's armor, priced and lifted: every mech chassis and vehicle variant side by side (bill, supply-equivalent
 * cost, lift class, access tier, structure plus armor capacity, speed, raw firepower, seats), the armor each buys per
 * thousand credits of base-price materials and per lift, and the best four-gantry bay each lift tier can put on the
 * ground. Evidence rather than a test: it asserts nothing, and reads the shipped catalogs so it cannot drift.
 *
 * <p>Prices are the game's own base prices from {@code commodities.csv}, read-only from the install. They are a common
 * yardstick for the bill, not what the player pays: scarcity and market margin are not modelled. Firepower is raw
 * damage per second from the weapon definitions (a mech's stock weapons; a vehicle's turret): no hit chance, armor
 * rating, splash or flux, so it ranks weapons of one family and does not rank a mortar against a machine gun.
 */
@Tag("armor-economy-evidence")
class ArmorEconomyEvidence {

    private static final int BAY_GANTRIES = 4;

    private record Machine(String name, boolean vehicle, LiftClass lift, EquipmentAccessTier tier,
                           FabricationCost bill, float structure, float armor, float rating, float speed,
                           float dps, int seats, String note) {
        float durability() { return structure + armor; }
    }

    @Test
    void writesTheArmorEconomy() throws Exception {
        Path out = Path.of(System.getProperty("armorEconomy.dir", "build/reports/armor-economy"));
        Files.createDirectories(out);
        Map<String, Float> prices = prices();
        List<Machine> machines = machines();

        StringBuilder md = new StringBuilder();
        md.append("# Armor economy\n\nGenerated by `gradlew armorEconomyEvidence` from the shipped catalogs.\n\n");
        md.append("Prices (base, credits): ");
        for (Map.Entry<String, Float> e : prices.entrySet()) md.append(e.getKey()).append(' ').append(e.getValue().intValue()).append("; ");
        md.append("\n\n**Armor** is structure + armor capacity. **k-cr** is the bill at base prices in thousands. "
                + "**Armor/kcr** is armor per thousand credits of bill; **armor/lift** is armor per lift spent "
                + "(every machine spends one lift). DPS is raw weapon output only.\n\n");
        md.append("| machine | kind | lift | tier | bill (sup/mach/met/rare) | k-cr | structure | armor cap | armor | rating"
                + " | speed | DPS | seats | armor/kcr | armor/lift |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n");
        for (Machine m : machines) {
            float cost = cost(m.bill, prices);
            md.append(String.format(Locale.ROOT,
                    "| %s | %s | %s | %s | %s | %.1f | %.0f | %.0f | %.0f | %.0f | %.2f | %.1f | %d | %.1f | %.0f |\n",
                    m.name, m.vehicle ? "vehicle" : "mech", m.lift, m.tier, bill(m.bill), cost / 1000f,
                    m.structure, m.armor, m.durability(), m.rating, m.speed, m.dps, m.seats,
                    m.durability() / (cost / 1000f), m.durability()));
        }
        md.append("\nNotes: ");
        for (Machine m : machines) if (!m.note.isEmpty()) md.append(m.name).append(": ").append(m.note).append(" ");
        md.append("\n\n## Within each weight class (cost-effectiveness against the class's mech)\n\n");
        for (LiftClass lift : LiftClass.values()) {
            Machine mech = null;
            for (Machine m : machines) if (!m.vehicle && m.lift == lift) mech = m;
            if (mech == null) continue;
            float mechCost = cost(mech.bill, prices) / 1000f;
            md.append("**").append(lift).append("** (mech ").append(mech.name).append(": ")
                    .append(String.format(Locale.ROOT, "%.0f armor, %.1f kcr, %.1f armor/kcr)\n\n",
                            mech.durability(), mechCost, mech.durability() / mechCost));
            for (Machine m : machines) {
                if (!m.vehicle || m.lift != lift) continue;
                float c = cost(m.bill, prices) / 1000f;
                md.append(String.format(Locale.ROOT, "- %s: %.0f armor (%.2fx), %.1f kcr (%.2fx), %.1f armor/kcr (%.2fx the mech's)\n",
                        m.name, m.durability(), m.durability() / mech.durability(), c, c / mechCost,
                        m.durability() / c, (m.durability() / c) / (mech.durability() / mechCost)));
            }
            md.append('\n');
        }

        md.append("## Best bay by lift tier\n\nFour gantries; every machine type assumed owned in any quantity. "
                + "`LiftBudget` decides what is liftable.\n\n");
        md.append("| tier | machines | armor (all) | best mix | armor (mechs only) | best mechs | armor (vehicles only) | best vehicles |\n|---|---|---|---|---|---|---|---|\n");
        FittedBoat light = new FittedBoat(ShuttleType.BUFFALO, BoatFitting.STANDARD_PLATING, BoatFitting.STANDARD_DRIVE,
                BoatFitting.LIFT_CRADLE, "b1");
        FittedBoat heavy = new FittedBoat(ShuttleType.BUFFALO, BoatFitting.STANDARD_PLATING, BoatFitting.STANDARD_DRIVE,
                BoatFitting.HEAVY_CRADLE, "b1");
        Object[][] tiers = {
                {"starter: light cradle", light, false},
                {"mid: heavy cradle", heavy, false},
                {"late: Valkyrie (ship lift)", null, true},
                {"late+: Valkyrie and light cradle", light, true},
                {"late+: Valkyrie and heavy cradle", heavy, true}};
        for (Object[] tier : tiers) {
            FittedBoat boat = (FittedBoat) tier[1];
            boolean synthetic = (Boolean) tier[2];
            Best all = best(machines, boat, synthetic, 0);
            Best mechs = best(machines, boat, synthetic, 1);
            Best vehicles = best(machines, boat, synthetic, 2);
            md.append(String.format(Locale.ROOT, "| %s | %d | %.0f | %s | %.0f | %s | %.0f | %s |\n", tier[0],
                    all.names.size(), all.armor, all.names, mechs.armor, mechs.names, vehicles.armor, vehicles.names));
        }
        Files.writeString(out.resolve("summary.md"), md.toString());
        System.out.println(md);
    }

    private static final class Best {
        float armor;
        List<String> names = List.of();
    }

    /** Exhaustive best of up to {@link #BAY_GANTRIES} machines the budget can lift; {@code mode} 0 all, 1 mechs, 2 vehicles. */
    private static Best best(List<Machine> machines, FittedBoat boat, boolean synthetic, int mode) {
        List<Machine> pool = new ArrayList<>();
        for (Machine m : machines) {
            if (mode == 1 && m.vehicle) continue;
            if (mode == 2 && !m.vehicle) continue;
            pool.add(m);
        }
        Best best = new Best();
        search(pool, 0, new ArrayList<>(), boat, synthetic, best);
        return best;
    }

    private static void search(List<Machine> pool, int from, List<Machine> chosen, FittedBoat boat,
                               boolean synthetic, Best best) {
        if (!chosen.isEmpty()) {
            List<LiftClass> load = new ArrayList<>();
            float armor = 0f;
            for (Machine m : chosen) {
                load.add(m.lift);
                armor += m.durability();
            }
            LiftBudget budget = LiftBudget.forMission(boat, synthetic, ShuttleType.VALKYRIE, BAY_GANTRIES);
            if (budget.allocate(load, true) == null) return;
            if (armor > best.armor) {
                best.armor = armor;
                best.names = new ArrayList<>();
                for (Machine m : chosen) best.names.add(m.name);
            }
        }
        if (chosen.size() == BAY_GANTRIES) return;
        for (int i = from; i < pool.size(); i++) {
            chosen.add(pool.get(i));
            search(pool, i, chosen, boat, synthetic, best);
            chosen.remove(chosen.size() - 1);
        }
    }

    private static List<Machine> machines() {
        List<Machine> list = new ArrayList<>();
        for (MechFabricationCatalog.Recipe recipe : MechFabricationCatalog.chassis()) {
            MechVariant v = recipe.variant();
            float dps = 0f;
            for (MechMountSlot slot : MechMountSlot.values()) dps += weaponDps(v.stockWeapon(slot));
            list.add(new Machine(v.name(), false, v.liftClass(), MechPattern.of(v).accessTier(),
                    MechFabricationCatalog.standardFitCost(v),
                    v.maxStructure, v.armorCapacity, v.armorRating, v.moveSpeed, dps, 0,
                    "stock weapons " + (v.twoArmed() ? "2x " : "") + v.stockArmWeapon().name() + "/" + v.leftShoulder.name()
                            + (v.rightShoulder != null ? "/" + v.rightShoulder.name() : "")));
        }
        for (MechFabricationCatalog.Recipe recipe : MechFabricationCatalog.vehicles()) {
            VehicleType t = recipe.vehicle();
            StructureDef turret = t.turretStructure();
            float dps = 0f;
            String note = "";
            if (turret != null && turret.mount != null) {
                WeaponDef w = turret.mount.weapon;
                dps = w.damage * w.burstCount * w.projectilesPerShot / Math.max(0.01f, w.cooldown);
                if (w.aoeRadius > 0f) note = "turret has splash (radius " + w.aoeRadius + "), DPS understates it";
            }
            list.add(new Machine(t.name(), true, t.liftClass(), MechPattern.of(t).accessTier(), recipe.cost(),
                    t.maxStructure, t.maxArmor, t.armorRating, t.maxSpeed, dps, t.capacity, note));
        }
        return list;
    }

    private static float weaponDps(MechWeaponComponent c) {
        if (c == null) return 0f;
        WeaponDef w = c.weaponDef();
        return w.damage * c.projectilesPerTrigger / c.cycleSeconds();
    }

    private static float cost(FabricationCost bill, Map<String, Float> prices) {
        float total = 0f;
        for (FabricationCost.Line line : bill.lines()) {
            total += line.quantity() * prices.getOrDefault(line.commodityId(), 0f);
        }
        return total;
    }

    private static String bill(FabricationCost bill) {
        StringBuilder sb = new StringBuilder();
        for (FabricationCost.Line line : bill.lines()) {
            if (sb.length() > 0) sb.append('/');
            sb.append(line.quantity());
        }
        return sb.toString();
    }

    /** Base prices of the four bill commodities, read from the install's commodities.csv. */
    private static Map<String, Float> prices() throws Exception {
        Path csv = Path.of(System.getProperty("starsectorDir", "C:/Program Files (x86)/Fractal Softworks/Starsector"),
                "starsector-core/data/campaign/commodities.csv");
        Map<String, Float> prices = new HashMap<>();
        for (String line : Files.readAllLines(csv)) {
            String[] cells = line.split(",", -1);
            if (cells.length < 4 || cells[1].isBlank() || cells[0].equals("name")) continue;
            try {
                prices.put(cells[1], Float.parseFloat(cells[3]));
            } catch (NumberFormatException ignored) {
                // a row that is not a commodity price
            }
        }
        Map<String, Float> used = new java.util.LinkedHashMap<>();
        for (String id : List.of("supplies", "heavy_machinery", "metals", "rare_metals")) {
            used.put(id, prices.getOrDefault(id, 0f));
        }
        return used;
    }
}
